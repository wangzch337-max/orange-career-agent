"""Closed diagnostic vocabulary, deliberately without numeric quality scores."""

from enum import Enum


class EvaluationSeverity(str, Enum):
    BLOCKING = "BLOCKING"
    MAJOR = "MAJOR"
    MINOR = "MINOR"


class FailureTaxonomy(str, Enum):
    UNSUPPORTED_INFERENCE = "UNSUPPORTED_INFERENCE"
    EVIDENCE_OVERCLAIM = "EVIDENCE_OVERCLAIM"
    EVIDENCE_REFERENCE_INVALID = "EVIDENCE_REFERENCE_INVALID"
    UNCERTAINTY_COLLAPSED = "UNCERTAINTY_COLLAPSED"
    UNKNOWN_COLLAPSED_TO_GAP = "UNKNOWN_COLLAPSED_TO_GAP"
    GOAL_TYPE_MISCLASSIFICATION = "GOAL_TYPE_MISCLASSIFICATION"
    JOB_FACT_CONTAMINATION = "JOB_FACT_CONTAMINATION"
    JOB_REQUIREMENT_INVENTED = "JOB_REQUIREMENT_INVENTED"
    MATCH_RELATION_MISCLASSIFICATION = "MATCH_RELATION_MISCLASSIFICATION"
    MATCH_SCORE_INTRODUCED = "MATCH_SCORE_INTRODUCED"
    ROLE_RANKING_INTRODUCED = "ROLE_RANKING_INTRODUCED"
    AUTHORITY_VIOLATION = "AUTHORITY_VIOLATION"
    CANDIDATE_MEMORY_USED_AS_AUTHORITY = "CANDIDATE_MEMORY_USED_AS_AUTHORITY"
    STALE_MEMORY_USE = "STALE_MEMORY_USE"
    SUBJECT_LEAKAGE = "SUBJECT_LEAKAGE"
    LIFECYCLE_BYPASS = "LIFECYCLE_BYPASS"
    PROFILE_CONFIRMATION_BYPASS = "PROFILE_CONFIRMATION_BYPASS"
    PROFILE_VERSIONING_ERROR = "PROFILE_VERSIONING_ERROR"
    MEMORY_MUTATION_ON_READ = "MEMORY_MUTATION_ON_READ"
    PROVENANCE_MISSING = "PROVENANCE_MISSING"
    ACTION_UNGROUNDED = "ACTION_UNGROUNDED"
    ACTION_AUTO_CONFIRMED_CAPABILITY = "ACTION_AUTO_CONFIRMED_CAPABILITY"
    WORKFLOW_GATE_BYPASS = "WORKFLOW_GATE_BYPASS"
    CROSS_COMPONENT_INVARIANT_BREAK = "CROSS_COMPONENT_INVARIANT_BREAK"
    NETWORK_BOUNDARY_VIOLATION = "NETWORK_BOUNDARY_VIOLATION"
    PRIVATE_DATA_BOUNDARY_VIOLATION = "PRIVATE_DATA_BOUNDARY_VIOLATION"
    PRESENTATION_AMBIGUITY = "PRESENTATION_AMBIGUITY"


BLOCKING_CATEGORIES = frozenset({
    FailureTaxonomy.AUTHORITY_VIOLATION,
    FailureTaxonomy.CANDIDATE_MEMORY_USED_AS_AUTHORITY,
    FailureTaxonomy.STALE_MEMORY_USE,
    FailureTaxonomy.SUBJECT_LEAKAGE,
    FailureTaxonomy.LIFECYCLE_BYPASS,
    FailureTaxonomy.PROFILE_CONFIRMATION_BYPASS,
    FailureTaxonomy.PROFILE_VERSIONING_ERROR,
    FailureTaxonomy.MEMORY_MUTATION_ON_READ,
    FailureTaxonomy.WORKFLOW_GATE_BYPASS,
    FailureTaxonomy.NETWORK_BOUNDARY_VIOLATION,
    FailureTaxonomy.PRIVATE_DATA_BOUNDARY_VIOLATION,
    FailureTaxonomy.ACTION_AUTO_CONFIRMED_CAPABILITY,
})


def severity_for(category: FailureTaxonomy) -> EvaluationSeverity:
    if category in BLOCKING_CATEGORIES:
        return EvaluationSeverity.BLOCKING
    if category == FailureTaxonomy.PRESENTATION_AMBIGUITY:
        return EvaluationSeverity.MINOR
    return EvaluationSeverity.MAJOR
